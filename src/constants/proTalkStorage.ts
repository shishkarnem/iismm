/**
 * Normalizes any legacy `/file/<id>/<slug>`, `https://.../file/...`, `/og-hero-preview.*`, or `https://filestore.pro-talk.ru/...`
 * link into its canonical full original `https://file.pro-talk.ru/tgf/...` URL.
 */
export function normalizeProTalkMediaUrl(rawUrl?: string | null): string {
  if (!rawUrl || typeof rawUrl !== 'string') return '';
  const trimmed = rawUrl.trim();
  if (!trimmed) return '';

  if (/og-hero-preview\.png(\?|$)/i.test(trimmed)) return BRAND_ASSETS.socialLight;
  if (/og-hero-preview\.jpg(\?|$)/i.test(trimmed)) return BRAND_ASSETS.heroScreenshot;

  if (/^https?:\/\/filestore\.pro-talk\.ru\//i.test(trimmed)) {
    const hashPart = trimmed.replace(/^https?:\/\/filestore\.pro-talk\.ru\//i, '');
    // Replace old iismmlogo / heart hashes with fresh TGF brand assets when matched
    if (hashPart.startsWith('GgMpJwQ9JCkYKglyGHQPNFgWO1QkDTo2')) return BRAND_ASSETS.logo;
    if (hashPart.startsWith('GgMpJwQ9JCkYKglyGHQPNFk8O1QnDT8Y')) return BRAND_ASSETS.heartAvatar;
    return `https://file.pro-talk.ru/tgf/${hashPart}`;
  }

  if (!trimmed.includes('api.telegram.org/file/')) {
    const fileMatch = trimmed.match(/(?:^|https?:\/\/[^/]+)\/file\/([^/?#]+)(?:\/([^/?#]+))?/i);
    if (fileMatch) {
      const idOrKey = fileMatch[1] || '';
      const slug = (fileMatch[2] || '').toLowerCase();
      if (slug && LEGACY_FILE_SLUG_MAP[slug]) {
        return LEGACY_FILE_SLUG_MAP[slug];
      }
      if (LEGACY_FILE_KEY_MAP[idOrKey]) {
        return LEGACY_FILE_KEY_MAP[idOrKey];
      }
      if (LEGACY_FILE_SLUG_MAP[idOrKey.toLowerCase()]) {
        return LEGACY_FILE_SLUG_MAP[idOrKey.toLowerCase()];
      }
    }
  }

  return trimmed;
}

/**
 * Uploads a File/Blob directly to https://file.pro-talk.ru/tgf with X-Upload-Token and X-Preserve-Alpha: true,
 * returning the full original `https://file.pro-talk.ru/tgf/...` URL.
 */
export async function uploadFileDirectlyToProTalkTgf(
  file: File | Blob,
  filename?: string,
  uploadToken: string = PROTALK_TGF_UPLOAD_TOKEN
): Promise<string> {
  const formData = new FormData();
  const effectiveName = filename || (file instanceof File ? file.name : `upload_${Date.now()}.png`);
  formData.append('file', file, effectiveName);

  const response = await fetch(PROTALK_TGF_UPLOAD_URL, {
    method: 'POST',
    headers: {
      'X-Upload-Token': uploadToken || PROTALK_TGF_UPLOAD_TOKEN,
      'X-Preserve-Alpha': 'true'
    },
    body: formData
  });

  if (!response.ok) {
    throw new Error(`Ошибка загрузки в ProTalk Storage (${response.status})`);
  }

  const data = await response.json();
  const url = String(data?.url || '').trim();
  if (!url) {
    throw new Error('Сервер ProTalk Storage не вернул ссылку url');
  }
  return normalizeProTalkMediaUrl(url);
}
